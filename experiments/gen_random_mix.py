"""Generate the random-workload plans (plans/random_mix_{a,b,c}.txt).

    python experiments/gen_random_mix.py

Draws 30 workloads `mix:C,W,I` (C cpu-bound, W io-style, I interactive
processes) from a FIXED seed, so anyone regenerating gets identical plans, and
runs each under eight policy configurations, 3 seeds per line. The point is to
test conclusions on workloads that were NOT picked or tuned by hand.

Each mix has 1-8 CPU-bound processes, 0-3 io-style and 0-3 interactive, at least
one non-CPU-bound process (otherwise there is no latency to measure), and at
most 14 processes in total.

The predictions below were written before the plans were first run.
"""
import os
import random

SEED = 2026
POLICIES = ["rr", "mlfq", "fair", "hint", "hfair", "hfair16", "hint hints=wrong", "hfair hints=wrong"]
HEADER = """# Random workloads (generated by experiments/gen_random_mix.py, seed {seed}); part {part}/3.
# PREDICTIONS, WRITTEN BEFORE RUNNING (about the hfair design, which was formulated
# after looking at the data it was meant to explain, so it needs a fresh test):
#   M1. Whenever a mix contains an interactive process, hfair and fair give it
#       p95 wake-up latency <= 50 us (they did in every hand-picked workload).
#   M2. hfair's switch count lies between hint's and fair's in every mix, and
#       is never more than 5% above fair's.
#   M3. With wrong hints, hfair's interactive latency stays <= 50 us in every
#       mix, while hint's exceeds 10 ms in at least a third of the mixes that have
#       both CPU-bound and interactive processes.
#   M4. Makespan is within 1% across all policies within each mix.
#   M5. mlfq (default 200 ms boost) has the worst interactive latency of the
#       hint-free policies in most mixes.
# A prediction that fails gets reported as failed.
"""


HEADER2 = """# Random workloads, STAGGERED interactive periods (13/15/17 ms): mix2:C,W,I.
# Generated by experiments/gen_random_mix.py, seed {seed}; part {part}/3. Same mixes and
# policies as random_mix_*.txt. Written because that run's M1/M3a/M5 failed for a reason
# that was my prediction's fault: all interactive processes slept exactly 15 ms, so
# with two or more they woke in lockstep and queued behind each other (~0.5 ms),
# which no scheduler can avoid. These predictions were written BEFORE this run:
#   M1'. In at least 90% of the mixes that have an interactive process, fair and hfair
#        give p95 wake-up latency <= 100 us.
#   M2.  hint <= hfair <= 1.05 x fair in context switches, in every mix (a repeat of M2,
#        which held 30/30 on the first random run).
#   M3a'. hfair with WRONG hints: interactive p95 <= 100 us in at least 90% of those mixes.
#   M3b. hint with WRONG hints exceeds 10 ms in at least a third of the mixes that have
#        both CPU-bound and interactive processes.
#   M4'. Makespan within 1.5% across rr/mlfq/fair/hint/hfair/hfair16 in every mix.
#   M5'. In every mix with an interactive process, rr's AND mlfq's p95 are worse than fair's.
#   M6.  (out of sample for the aging finding F11) hint with correct hints: p95 <= 100 us
#        in at least 90% of the mixes with <= 5 CPU-bound processes, AND above 100 us in
#        at least one mix with >= 7 CPU-bound processes.
# A prediction that fails gets reported as failed.
"""


def draw():
    rng = random.Random(SEED)
    mixes = []
    while len(mixes) < 30:
        c, w, i = rng.randint(1, 8), rng.randint(0, 3), rng.randint(0, 3)
        if w + i == 0 or c + w + i > 14 or (c, w, i) in mixes:
            continue
        mixes.append((c, w, i))
    return mixes


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    mixes = draw()
    for part in range(3):
        chunk = mixes[part * 10:(part + 1) * 10]
        lines = [HEADER.format(seed=SEED, part=part + 1).rstrip("\n")]
        for c, w, i in chunk:
            for pol in POLICIES:
                lines.append(f"repeat 3 bench mix:{c},{w},{i} {pol}")
        path = os.path.join(here, "plans", f"random_mix_{'abc'[part]}.txt")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print(path, len(chunk) * len(POLICIES) * 3, "runs")

        lines2 = [HEADER2.format(seed=SEED, part=part + 1).rstrip("\n")]
        for c, w, i in chunk:
            for pol in POLICIES:
                lines2.append(f"repeat 3 bench mix2:{c},{w},{i} {pol}")
        path2 = os.path.join(here, "plans", f"random_mix2_{'abc'[part]}.txt")
        with open(path2, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines2) + "\n")
        print(path2, len(chunk) * len(POLICIES) * 3, "runs")
    print("mixes (cpu,io,interactive):", mixes)


if __name__ == "__main__":
    main()
