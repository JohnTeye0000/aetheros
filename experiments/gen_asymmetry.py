"""Generate plans/asymmetry.txt (F19): who pays for a wrong compiler hint?

    python experiments/gen_asymmetry.py

Picks corpus programs (F17) that a classifier got wrong in each direction,
using the measured classes from results/release/hint_corpus:
  LIGHT  measured cpu (or io with >= 1 ms of CPU per wait), counted analysis
         guessed interactive -- the too-light kind;
  HEAVY  measured interactive, safe analysis guessed cpu -- the too-heavy kind.
For each it writes two .axe copies, one carrying the counted hint and one the
safe hint (plainlang/asym/*), and runs each next to p_int (a real interactive
program) and p_cpu (a CPU hog) under hint and hfair, 3 seeds.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from hint_accuracy import measured, PLAINLANG  # noqa: E402

OUT = os.path.join(HERE, "plainlang", "asym")
MAX_EACH = 5
HEADER = """# Who pays for a wrong compiler hint? (F19) Generated by gen_asymmetry.py.
# Each line: one mislabelled corpus program + p_int (interactive) + p_cpu (hog).
# hNNN_c.axe carries the counted analysis's hint, hNNN_s.axe the safe one's.
# PREDICTIONS, WRITTEN BEFORE RUNNING:
#   Y1. LIGHT programs under hint with their (too-light, interactive) counted
#       hint: p_int's p95 wake-up latency > 1 ms in every case -- the neighbour
#       pays.
#   Y2. HEAVY programs under hint with their (too-heavy, cpu) safe hint: the
#       program's OWN p95 > 1 ms in every case, while p_int's stays <= 100 us --
#       the program pays, not the neighbour.
#   Y3. Under hfair, whatever the hint, p_int's p95 <= 100 us in every line.
"""


def main():
    sys.path.insert(0, PLAINLANG)
    import plainaxe
    import plainhint
    os.makedirs(OUT, exist_ok=True)
    res = os.path.join(HERE, "results", "release", "hint_corpus", "results.csv")
    light, heavy = [], []
    for r in csv.DictReader(open(res, encoding="utf-8")):
        name = r["prog"][:-4]
        src = open(os.path.join(HERE, "plainlang", "corpus", name + ".plang"), encoding="utf-8").read()
        tree = plainaxe.parse(src)
        hc, hs = plainhint.infer(tree, "counted")[0], plainhint.infer(tree, "safe")[0]
        cpu, blocks = int(r["cpu_us"]), int(r["blocks"])
        truth = measured(cpu, blocks)
        heavy_burst = truth == "cpu" or (truth == "io" and cpu / blocks >= 1000)
        if heavy_burst and hc == "interactive" and len(light) < MAX_EACH:
            light.append((name, src, hc, hs))
        if truth == "interactive" and hs == "cpu" and len(heavy) < MAX_EACH:
            heavy.append((name, src, hc, hs))
    plan = [HEADER.rstrip("\n")]
    for group, items in (("LIGHT", light), ("HEAVY", heavy)):
        plan.append(f"# {group}: " + ", ".join(f"{n} (counted {hc}, safe {hs})" for n, _, hc, hs in items))
        for name, src, hc, hs in items:
            code = plainaxe.compile_axe(src)
            for tag, h in (("c", hc), ("s", hs)):
                fn = f"{name}_{tag}.axe"
                with open(os.path.join(OUT, fn), "w", encoding="utf-8", newline="\n") as f:
                    f.write(plainaxe.to_axe_text(code, h, fn, f"hint from the {tag} analysis"))
            for pol in ("hint", "hfair"):
                for tag in ("c", "s"):
                    plan.append(f"repeat 3 bench files:{name}_{tag}.axe+p_int.axe+p_cpu.axe {pol}")
    with open(os.path.join(HERE, "plans", "asymmetry.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(plan) + "\n")
    print(f"LIGHT {[n for n, *_ in light]}  HEAVY {[n for n, *_ in heavy]}  "
          f"{len(plan) - 3} plan lines")


if __name__ == "__main__":
    main()
