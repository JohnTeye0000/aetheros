"""Generate a random corpus of PlainLang programs to measure the hint
classifier's accuracy (F17): plans/hint_corpus.txt + plainlang/corpus/*.

    python experiments/gen_hint_corpus.py [--n 150]

Needs the PlainLang repo next to this one (../plainlang). Every program is
drawn from a FIXED seed, compiled with plainaxe.py, and its static hint is
recorded under both analyses (basic, counted) in corpus/hints.csv. The plan
runs each program ALONE under `fair` (which ignores hints), so the kernel's
measurements -- CPU time and number of waits -- are the ground truth the
static guess is scored against by hint_accuracy.py.

Programs are built from the shapes real code has and the classifier may or may
not see through: `repeat`/`count` loops, counted `while` loops, `while` loops
whose counter is aliased through another variable, loop bounds returned by a
function, waits gated by an `if`, and two-phase programs.
"""
import argparse
import csv
import math
import os
import random
import sys

SEED = 2027
HERE = os.path.dirname(os.path.abspath(__file__))
PLAINLANG = os.path.normpath(os.path.join(HERE, "..", "..", "plainlang"))
OUT = os.path.join(HERE, "plainlang", "corpus")
MAX_ITERS = 400_000          # bounds every program's CPU time (~50 ms)
MAX_WAIT_S = 0.6             # bounds every program's total sleeping

HEADER = """# Hint-classifier accuracy on {n} random PlainLang programs (F17).
# Generated by experiments/gen_hint_corpus.py, seed {seed}. Each program runs
# ALONE under fair (hints ignored); the kernel's CPU time and wait count are the
# ground truth. Measured class, from CPU time per wait (the classifier's own
# thresholds converted at its documented ~40 ns per operation):
#   no waits: cpu if >= 2 ms CPU, else none;  per wait <= 0.1 ms: interactive;
#   <= 4 ms: io;  otherwise cpu.
# PREDICTIONS, WRITTEN BEFORE RUNNING:
#   A1. counted analysis agrees with the measured class on >= 70% of programs.
#   A2. counted beats basic by >= 10 points (basic guesses every while loop).
#   A3. "gross" errors (cpu <-> interactive, the kind F4 shows is harmful under
#       hint-as-priority) are < 10% under counted, and >= half of them come
#       from shapes the docstring names as blind spots: function-bound loops,
#       aliased counters, gated waits.
#   A4. Errors are mostly near a threshold: >= half of counted's misses have a
#       measured CPU-per-wait within a factor of 3 of the boundary crossed.
"""


def loop_block(rng, k, tag):
    """A loop doing about k iterations of light work, plus its shape name."""
    kind = rng.choice(["repeat", "count", "while", "aliased", "function"])
    s = f"s{tag}"
    if kind == "repeat":
        body = [f"repeat {k} times", f"set {s} to {s} plus 1", "end"]
    elif kind == "count":
        body = [f"count i{tag} from 1 to {k}", f"set {s} to {s} plus i{tag}", "end"]
    elif kind == "while":
        body = [f"set x{tag} to 0", f"while x{tag} is less than {k}", f"set x{tag} to x{tag} plus 1",
                f"set {s} to {s} plus x{tag}", "end"]
    elif kind == "aliased":
        body = [f"set x{tag} to 0", f"set y{tag} to 0", f"while y{tag} is less than {k}",
                f"set x{tag} to x{tag} plus 1", f"set y{tag} to x{tag}", "end"]
    else:
        body = [f"set n{tag} to bound{tag} with {k}", f"set x{tag} to 0", f"while x{tag} is less than n{tag}",
                f"set x{tag} to x{tag} plus 1", "end"]
    return kind, [f"set {s} to 0"] + body


def segment(rng, tag):
    """One phase: an outer loop of r rounds of (work, maybe a wait)."""
    for _ in range(100):
        r = rng.randint(3, 40)
        k = int(math.exp(rng.uniform(math.log(5), math.log(60_000))))
        d = rng.choice([0.002, 0.004, 0.008, 0.015])
        wait = rng.choices(["always", "gated", "never"], weights=[6, 2, 2])[0]
        if r * k <= MAX_ITERS and r * d <= MAX_WAIT_S:
            break
    kind, work = loop_block(rng, k, tag)
    lines = [f"count r{tag} from 1 to {r}"] + work
    if wait == "always":
        lines.append(f"wait {d}")
    elif wait == "gated":
        g = rng.randint(2, 5)
        lines += [f"if remainder of r{tag} and {g} is 0 then", f"wait {d}", "end"]
    lines.append("end")
    funcs = [f"define bound{tag} with a", "return a", "end"] if kind == "function" else []
    return funcs, lines, f"{kind}/{wait}"


def program(rng):
    phases = 2 if rng.random() < 0.25 else 1
    funcs, body, shapes = [], [], []
    for p in range(phases):
        f, b, sh = segment(rng, chr(ord("a") + p))
        funcs += f
        body += b
        shapes.append(sh)
    return "\n".join(funcs + body + ['say "done"']) + "\n", "+".join(shapes)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=150)
    a = ap.parse_args()
    sys.path.insert(0, PLAINLANG)
    import plainaxe
    import plainhint
    os.makedirs(OUT, exist_ok=True)
    rng = random.Random(SEED)
    rows, plan = [], [HEADER.format(n=a.n, seed=SEED).rstrip("\n")]
    for i in range(a.n):
        src, shape = program(rng)
        name = f"h{i:03d}"
        tree = plainaxe.parse(src)
        hb, _ = plainhint.infer(tree, "basic")
        hc, why = plainhint.infer(tree, "counted")
        code = plainaxe.compile_axe(src)
        with open(os.path.join(OUT, name + ".plang"), "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
        with open(os.path.join(OUT, name + ".axe"), "w", encoding="utf-8", newline="\n") as f:
            f.write(plainaxe.to_axe_text(code, hc, name + ".axe", "analysis: counted\n" + why))
        rows.append({"prog": name + ".axe", "shape": shape, "basic": hb, "counted": hc})
        plan.append(f"bench files:{name}.axe fair")
    with open(os.path.join(OUT, "hints.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["prog", "shape", "basic", "counted"])
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(HERE, "plans", "hint_corpus.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(plan) + "\n")
    size = sum(os.path.getsize(os.path.join(OUT, r["prog"])) for r in rows)
    print(f"{a.n} programs, {size / 1024:.0f} KiB of .axe; static hints (counted):",
          {h: sum(r["counted"] == h for r in rows) for h in ("cpu", "io", "interactive", "none")})


if __name__ == "__main__":
    main()
